/** Derive opt-in presets from pinned official compositions; --check detects upstream drift. */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
const here = new URL('./', import.meta.url)
const pieces = ['standard', 'ptc', 'cordis'].map((id, index) => {
  const official = readFileSync(new URL(`../../bundle/web-app/presets/${id}.patch.yml`, here), 'utf8')
  const provider = "name: '@deepseek-ai/dsh-compaction-basic'"
  if (official.split(provider).length !== 2) throw Error(`Official ${id} compaction seat changed; review the adapter`)
  return official.slice(official.indexOf('- insert:'))
    .replace(`id: preset-${id}`, `id: preset-notebook-${id}`)
    .replace(`id: ${id}\n`, `id: notebook-${id}\n        name: 'Notebook · ${id}'\n`)
    .replace(/order: \d+/, `order: ${10 + index}`)
    .replace(provider, "name: '@nidofy/dsh-desktop-extras/compaction'")
})
const output = '# Generated by generate-context-presets.mjs from the pinned official presets.\n' + pieces.join('\n')
const destination = fileURLToPath(new URL('./context-presets.patch.yml', here))
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output) throw Error('Derived notebook presets are stale')
} else writeFileSync(destination, output)
