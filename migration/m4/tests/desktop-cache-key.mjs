import assert from 'node:assert/strict';
import {readFileSync,mkdtempSync,mkdirSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {desktopCacheKeyOptions} from '../../../packages/nidofy/desktop-extras/src/legacy/desktop-cache-key.mjs';
const profile = {provider:'desktop-internal',api:'openai-completions',baseURL:'https://synthetic.invalid/v1',desktopCacheKey:{mode:'session',models:['model-a']}};
const state = {home:resolve('.build/synthetic-cache-home'),key:Buffer.alloc(32,7)};
const payload = {messages:[{role:'user',content:'synthetic'}],tools:[{type:'function',function:{name:'read'}}],prompt_cache_key:'native-session-id',prompt_cache_retention:'24h'};
const send = (p=profile,m={id:'model-a'},o={sessionId:'private-session'},s=state) => desktopCacheKeyOptions(p,m,o,s).onPayload?.(payload)??payload;
const result = send(), key = result.prompt_cache_key;
assert.match(key,/^dsh_[A-Za-z0-9_-]{43}$/); assert(!key.includes('private-session'));
assert.equal(send().prompt_cache_key,key);
assert.notEqual(send(profile,{id:'model-a'},{sessionId:'another-session'}).prompt_cache_key,key);
assert.notEqual(send({...profile,baseURL:'https://other.invalid/v1'}).prompt_cache_key,key);
assert.notEqual(send(profile,{id:'model-a'},{sessionId:'private-session'},{...state,home:resolve('.build/other-home')}).prompt_cache_key,key);
assert.notEqual(send(profile,{id:'model-a'},{sessionId:'private-session'},{...state,key:Buffer.alloc(32,8)}).prompt_cache_key,key);
assert.notEqual(send({...profile,desktopCacheKey:{mode:'session',models:['model-b']}},{id:'model-b'}).prompt_cache_key,key);
assert.equal(send(profile,{id:'model-b'}).prompt_cache_key,undefined);
assert.equal(send(profile,{id:'model-a'},{}).prompt_cache_key,undefined);
assert.equal(send({...profile,desktopCacheKey:{mode:'off'}}).prompt_cache_key,undefined);
assert.equal(send({...profile,desktopCacheKey:{mode:'native'}}),payload);
assert.equal(send({...profile,desktopCacheKey:undefined}),payload);
assert.equal(send({...profile,api:'anthropic-messages'}),payload);
assert.equal(send({...profile,provider:'another-provider'}),payload);
const knownState={...state,managedProvider:'zai-coding-cn'};
assert.match(send({...profile,provider:'zai-coding-cn'},{id:'model-a'},{sessionId:'private-session'},knownState).prompt_cache_key,/^dsh_/);
assert.notEqual(send({...profile,provider:'zai-coding-cn'},{id:'model-a'},{sessionId:'private-session'},knownState).prompt_cache_key,key,'managed provider is part of the key scope');
assert.equal(send(profile,{id:'model-a'},{sessionId:'private-session'},knownState),payload,'retired desktop-internal route cannot receive the active provider policy');
assert.deepEqual({...result,prompt_cache_key:payload.prompt_cache_key},payload);
assert.equal(payload.prompt_cache_key,'native-session-id','original payload stays immutable');
const captured = desktopCacheKeyOptions(profile,{id:'model-a'},{sessionId:'private-session'},state);
state.key = Buffer.alloc(32,9); assert.equal(captured.onPayload(payload).prompt_cache_key,key,'prepared stream key remains stable');
console.log("PASS cache policy scopes and immutable payload; official prepare-payload integration covered by packaged smoke");
