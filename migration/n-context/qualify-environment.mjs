import assert from 'node:assert/strict'
import { writeFileSync, mkdtempSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'
export async function qualifyEnvironment({application,page,until,run,result,cwd,sessionId}) {
  const git=(...args)=>execFileSync('git',['-C',cwd,...args],{windowsHide:true,encoding:'utf8'}).trim()
  const card=page.locator('.nidofy-environment'), detail=page.locator('.nidofy-detail')
  const initialWindows=application.windows().length
  await card.getByRole('button',{name:/^Changes/}).click()
  await detail.locator('.nidofy-change-list button').first().waitFor()
  await detail.locator('.nidofy-change-list button').first().click()
  await until(async()=> (await detail.locator('pre').innerText()).includes('+updated fixture'), 'inline patch')
  assert.equal(application.windows().length,initialWindows)
  const geometry=await page.evaluate(()=>({main:document.querySelector('[data-shell-main]').getBoundingClientRect().right,dock:document.querySelector('.nidofy-dock').getBoundingClientRect().x,overflow:document.documentElement.scrollWidth>innerWidth+1}))
  assert.ok(geometry.main<=geometry.dock+.1);assert.equal(geometry.overflow,false)
  await page.screenshot({path:join(run,'environment-changes.png')})
  result.checks.environmentInlinePatch=true
  await card.getByRole('button',{name:'Local git',exact:true}).click()
  assert.ok((await detail.innerText()).includes('Repository root'))
  assert.ok((await detail.innerText()).includes(cwd))
  await card.locator('.nidofy-explorer > .nidofy-row').last().click()
  await detail.getByRole('button',{name:'Switch branch',exact:true}).click()
  assert.equal(await detail.locator('select').inputValue(),'feature')
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await until(async()=> (await card.locator('[role="alert"]').count())>0,'dirty branch refused')
  assert.equal(git('branch','--show-current'),'main')
  result.checks.environmentDirtySwitchRefused=true
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await card.locator('.nidofy-action-menu').getByRole('button',{name:'Commit',exact:true}).click()
  git('add','note.txt')
  await detail.getByLabel('Commit message', {exact:false}).fill('environment fixture commit')
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).waitFor()
  const before=git('rev-parse','HEAD')
  assert.equal(git('log','-1','--format=%s'),'baseline')
  await detail.getByRole('button',{name:'Cancel preview',exact:true}).click()
  assert.equal(git('rev-parse','HEAD'),before)
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).click()
  await until(()=>git('log','-1','--format=%s')==='environment fixture commit','commit confirmed')
  await until(async()=> (await card.innerText()).includes('Operation completed'),'commit UI settled')
  result.checks.environmentCommitRequiresConfirmation=true
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await card.locator('.nidofy-action-menu').getByRole('button',{name:'Create branch',exact:true}).click()
  await detail.getByLabel('New branch name', {exact:true}).fill('inline-created')
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).waitFor()
  assert.equal(git('branch','--show-current'),'main')
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).click()
  await until(()=>git('branch','--show-current')==='inline-created','branch created')
  await until(async()=> (await card.innerText()).includes('Operation completed'),'create UI settled')
  result.checks.environmentCreateBranchConfirmed=true
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await card.locator('.nidofy-action-menu').getByRole('button',{name:'Switch branch',exact:true}).click()
  await detail.locator('select').selectOption('feature')
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).waitFor()
  writeFileSync(join(cwd,'new-file.txt'),'changed after preview')
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).click()
  await until(async()=> (await card.locator('[role="alert"]').innerText()).includes('OPERATION_NOT_CONFIRMED'),'stale preview refused')
  assert.equal(git('branch','--show-current'),'inline-created')
  result.checks.environmentStalePreviewRefused=true
  const bare=join(run,'remote.git')
  execFileSync('git',['init','--bare',bare],{windowsHide:true})
  git('remote','add','fixture',bare)
  await card.getByRole('button',{name:'Refresh',exact:true}).click()
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await card.locator('.nidofy-action-menu').getByRole('button',{name:'Push',exact:true}).click()
  await until(async()=> (await detail.locator('select option').allTextContents()).includes('fixture'),'remote refreshed')
  await detail.locator('select').selectOption('fixture')
  await detail.getByRole('button',{name:'Preview operation',exact:true}).click()
  await detail.getByRole('button',{name:'Confirm operation',exact:true}).waitFor()
  assert.equal(execFileSync('git',['--git-dir',bare,'for-each-ref'],{encoding:'utf8',windowsHide:true}).trim(),'')
  await detail.getByRole('button',{name:'Cancel preview',exact:true}).click()
  result.checks.environmentPushPreviewNoMutation=true
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await page.locator('.nidofy-workspace').click()
  // Pointer outside the explorer closes its action menu.
  assert.equal(await card.locator('.nidofy-action-menu').count(),0)
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  await page.keyboard.press('Escape')
  assert.equal(await detail.count(),0)
  assert.equal(await card.locator('.nidofy-action-menu').count(),0)
  result.checks.environmentMenuDismissal=true
  await card.getByRole('button',{name:'Connections',exact:true}).click()
  assert.equal(application.windows().length,initialWindows)
  assert.ok((await detail.innerText()).includes('Open connection editor'))
  await card.getByRole('button',{name:'Local git',exact:true}).click()
  await detail.getByRole('button',{name:'Open engineering workbench',exact:false}).click()
  await until(()=>application.windows().length>initialWindows,'explicit workbench')
  for(const p of application.windows())if(p!==page)await p.close()
  result.checks.environmentExplicitWorkbenchOnly=true
  await card.getByRole('button',{name:'Close details',exact:true}).click()
  await card.getByRole('button',{name:'Local git',exact:true}).click()
  const plain=mkdtempSync(join(tmpdir(),'nidofy-no-repository-'))
  const second=await page.evaluate(async cwd=>{
    const method='session/create',response=await fetch('/api/'+method,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({type:'client-request',rpcId:crypto.randomUUID(),method,payload:{args:{request:{cwd}}}})})
    const value=await response.json();if(!value.result.ok)throw Error(JSON.stringify(value.result));return value.result.value.sessionId
  },plain)
  const navigate=async id=>page.evaluate(id=>{const c=new BroadcastChannel('nidofy-pet-navigation');c.postMessage({sessionId:id});c.close()},id)
  await navigate(second)
  await until(async()=> (await card.locator('.nidofy-path').innerText()).includes(plain),'new context')
  assert.equal(await detail.count(),0)
  await card.getByRole('button',{name:'Repository actions',exact:true}).click()
  assert.equal(await card.locator('.nidofy-action-menu button:disabled').count(),4)
  await navigate(sessionId)
  await until(async()=> (await card.locator('.nidofy-path').innerText()).includes(cwd),'context restored')
  assert.equal(await detail.count(),0)
  result.checks.environmentSessionSwitchAndNoRepository=true
  await page.evaluate(async()=>{
    const method='settings/mutate';await fetch('/api/'+method,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({type:'client-request',rpcId:crypto.randomUUID(),method,payload:{args:{ns:'locale',ops:[{op:'set',path:['preference'],value:'zh'}]}}})})
  })
  await until(async()=> (await card.innerText()).includes('环境信息'),'localized details')
  await card.getByRole('button',{name:'本地 git',exact:true}).click()
  await until(async()=> (await detail.innerText()).includes('仓库根目录'),'localized repository fields')
  await page.screenshot({path:join(run,'environment-zh-local.png')})
  await card.screenshot({path:join(run,'environment-card.png')})
  result.checks.environmentLocalizedDetails=true
}
